/**
 * Знак вердикта (облик, шаг 3, 23.10.2026): «Допуск» — песочный, залитый, как растущие свечи на мониторах
 * сцены; «Отказ» — стальной, контуром, как падающие. Единственный цветной знак на странице: стоит только
 * там, где есть настоящее решение (карточка на первом экране, сделки, четыре вопроса). Стили — v3-skin.css.
 */
export default function Verdict({ ok }: { ok: boolean }) {
  return <span className={`verdict ${ok ? 'verdict--ok' : 'verdict--no'}`}>{ok ? 'Допуск' : 'Отказ'}</span>;
}
