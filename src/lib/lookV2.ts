/**
 * Облик сайта, шаг 1 (23.10.2026, план «Облик TRADELIKETYO», Сергей: «Да, начинай первый шаг»).
 *
 * Пока Сергей смотрит пробу, новый вид включается только адресом с ?v2, посетители видят прежний:
 * без номеров и капса над разделами, без точек-разделителей и стрелок, заголовки одним цветом.
 * Стили — styles/look-v2.css (под html.look-v2), тексты — v2('было', 'стало') в компонентах.
 *
 * После его «ставь» флаг убирается целиком: в компонентах остаётся только «стало», правила
 * из look-v2.css переезжают в основные стили без html.look-v2, этот файл удаляется.
 */
export const V2 = typeof window !== 'undefined' && new URLSearchParams(window.location.search).has('v2');

// класс ставится до первой отрисовки: модуль грузится раньше, чем React рисует страницу
if (V2) document.documentElement.classList.add('look-v2');

export const v2 = <T,>(was: T, now: T): T => (V2 ? now : was);
