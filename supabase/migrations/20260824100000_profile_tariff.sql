-- Маркер тарифа у ученика.
--
-- Доступ к курсам и тариф — разные вещи: доступ говорит, какие материалы
-- открыты, а тариф — что человек купил и на каком уровне сопровождения он
-- находится. По записям course_access это не восстанавливается: один и тот же
-- набор курсов может быть выдан на разных условиях.
--
-- Значение проставляет админ: при выдаче доступа или руками в карточке.
-- У тех, кто зарегистрировался раньше, поле пустое, пока владелец не проставит.
-- Свободный text без CHECK намеренно: тарифы переименовываются (Trade OS стал
-- Trade OS Plus), и ограничение пришлось бы менять миграцией каждый раз.

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS tariff text;

COMMENT ON COLUMN public.profiles.tariff IS
  'Ключ тарифа: trade_system | practicum | trade_os_plus | vip | ecosystem. NULL — не проставлен.';
